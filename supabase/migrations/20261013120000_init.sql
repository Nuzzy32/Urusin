-- ponytail: haversine full-scan atas mitra approved; ganti ke PostGIS + index GiST
-- kalau mitra sudah ribuan.
create or replace function public.nearby_mitras(
  p_lat double precision,
  p_lng double precision,
  p_category_id int default null,
  p_radius_km double precision default 5
)
returns table (
  mitra_id uuid, name text, avatar_url text, bio text, avg_rating numeric,
  total_reviews int, jobs_done int, years_experience int, sample_review text,
  price_min int, price_max int, available_text text, eta_text text,
  distance_km double precision, primary_category_id int
)
language sql stable security definer set search_path = '' as $$
  select m.mitra_id, u.name, m.avatar_url, m.bio, m.avg_rating, m.total_reviews,
         m.jobs_done, m.years_experience, m.sample_review, m.price_min, m.price_max,
         m.available_text, m.eta_text, round(d.km::numeric, 1)::double precision, m.primary_category_id
  from public.mitras m
  join public.users u on u.user_id = m.mitra_id
  join public.mitra_locations l on l.mitra_id = m.mitra_id
  cross join lateral (
    select 6371 * 2 * asin(sqrt(
      power(sin(radians(l.lat - p_lat) / 2), 2) +
      cos(radians(p_lat)) * cos(radians(l.lat)) * power(sin(radians(l.lng - p_lng) / 2), 2)
    )) as km
  ) d
  where m.verification_status = 'approved'
    and m.is_available
    and d.km <= least(greatest(p_radius_km, 0.5), 50)
    and (p_category_id is null
         or m.primary_category_id = p_category_id
         or exists (select 1 from public.mitra_services s
                    where s.mitra_id = m.mitra_id and s.category_id = p_category_id))
  order by d.km
  limit 50;
$$;

-- Admin: setujui / tolak pendaftaran mitra. Approve = buat/aktifkan baris mitras
-- dan salin layanan, harga, jadwal dari pendaftaran.
create or replace function public.admin_review_application(
  p_application_id text,
  p_approve boolean,
  p_note text default null
)
returns void language plpgsql security definer set search_path = '' as $$
declare
  a public.worker_applications;
begin
  if not private.is_admin() then
    raise exception 'hanya admin' using errcode = '42501';
  end if;

  select * into a from public.worker_applications where id = p_application_id for update;
  if not found then
    raise exception 'pendaftaran % tidak ditemukan', p_application_id;
  end if;

  update public.worker_applications
  set status = case when p_approve then 'approved' else 'rejected' end,
      reviewer_note = p_note,
      reviewed_by = (select auth.uid()),
      reviewed_at = now()
  where id = a.id;

  if not p_approve then
    update public.mitras set verification_status = 'rejected', is_verified = false
    where mitra_id = a.user_id;
    perform private.refresh_mitra_stats(a.user_id);
    return;
  end if;

  update public.users set name = a.full_name
  where user_id = a.user_id and coalesce(name, '') = '' and a.full_name <> '';

  insert into public.mitras as m (
    mitra_id, verification_status, registration_status, is_verified, bio,
    price_min, price_max, primary_category_id
  )
  select a.user_id, 'approved', 'approved', true, a.bio,
         (select min(p.price_from) from public.worker_application_prices p where p.application_id = a.id),
         (select max(coalesce(p.price_to, p.price_from)) from public.worker_application_prices p where p.application_id = a.id),
         (select c.category_id
            from public.worker_application_services s
            join public.categories c
              on lower(s.service_name) in (lower(c.category_name), lower(c.display_name))
           where s.application_id = a.id
           order by s.is_sub_service, s.id
           limit 1)
  on conflict (mitra_id) do update set
    verification_status = 'approved',
    registration_status = 'approved',
    is_verified = true,
    bio = coalesce(excluded.bio, m.bio),
    price_min = coalesce(excluded.price_min, m.price_min),
    price_max = coalesce(excluded.price_max, m.price_max),
    primary_category_id = coalesce(excluded.primary_category_id, m.primary_category_id);

  delete from public.mitra_services where mitra_id = a.user_id;
  insert into public.mitra_services (mitra_id, category_id, service_name, price_min, price_max)
  select a.user_id,
         (select c.category_id from public.categories c
           where lower(p.service_name) in (lower(c.category_name), lower(c.display_name)) limit 1),
         p.service_name,
         coalesce(p.price_from, 0),
         case when p.price_to >= coalesce(p.price_from, 0) then p.price_to end
  from public.worker_application_prices p
  where p.application_id = a.id;

  insert into public.mitra_schedules (mitra_id, day_name, start_time, end_time)
  select distinct on (s.day_name) a.user_id, s.day_name,
         coalesce(nullif(s.start_time, ''), '08:00')::time,
         coalesce(nullif(s.end_time, ''), '17:00')::time
  from public.worker_application_schedules s
  where s.application_id = a.id
  order by s.day_name, s.id
  on conflict (mitra_id, day_name) do update
    set start_time = excluded.start_time, end_time = excluded.end_time;

  -- Template quick reply bawaan (PRD: terima order, konfirmasi harga, info terlambat).
  if not exists (select 1 from public.mitra_quick_replies where mitra_id = a.user_id) then
    insert into public.mitra_quick_replies (mitra_id, title, body, sort_order) values
      (a.user_id, 'Terima order', 'Halo, order Anda sudah saya terima. Saya akan datang sesuai jadwal.', 1),
      (a.user_id, 'Konfirmasi harga', 'Setelah dicek, harga final pekerjaan ini Rp{harga}. Apakah disetujui sebelum saya mulai?', 2),
      (a.user_id, 'Info terlambat', 'Mohon maaf, saya sedikit terlambat. Perkiraan tiba {menit} menit lagi.', 3);
  end if;

