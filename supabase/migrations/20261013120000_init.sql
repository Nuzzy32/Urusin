-- ───────────────────────── statistik & badge otomatis ─────────────────────────

create or replace function private.refresh_mitra_stats(p_mitra uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if p_mitra is null then return; end if;

  update public.mitras m set
    avg_rating    = coalesce((select round(avg(r.rating), 2) from public.reviews r where r.worker_id = p_mitra), 0),
    total_reviews = (select count(*) from public.reviews r where r.worker_id = p_mitra),
    jobs_done     = (select count(*) from public.bookings b
                     where b.worker_id = p_mitra and b.status in ('completed', 'reviewed'))
  where m.mitra_id = p_mitra;

  delete from public.mitra_badges where mitra_id = p_mitra;
  insert into public.mitra_badges (mitra_id, badge_id)
  select p_mitra, b.badge_id from public.badges b
  where (b.badge_key = 'verified' and exists (
          select 1 from public.mitras where mitra_id = p_mitra and verification_status = 'approved'))
     -- ≥3 laporan harga, ≥80% sesuai estimasi
     or (b.badge_key = 'price_transparent' and (
          select count(*) >= 3 and avg(case when r.was_price_within_estimate then 1 else 0 end) >= 0.8
          from public.reviews r where r.worker_id = p_mitra and r.was_price_within_estimate is not null))
     -- ≥5 ulasan, rata-rata ≥4.7
     or (b.badge_key = 'top_rated' and (
          select count(*) >= 5 and avg(r.rating) >= 4.7 from public.reviews r where r.worker_id = p_mitra))
     -- ≥3 order diterima, rata-rata respon ≤15 menit
     or (b.badge_key = 'fast_response' and (
          select count(*) >= 3 and avg(bk.accepted_at - bk.created_at) <= interval '15 minutes'
          from public.bookings bk where bk.worker_id = p_mitra and bk.accepted_at is not null));
end $$;

create or replace function private.reviews_refresh()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  perform private.refresh_mitra_stats(coalesce(new.worker_id, old.worker_id));
  if tg_op = 'UPDATE' and old.worker_id is distinct from new.worker_id then
    perform private.refresh_mitra_stats(old.worker_id);
  end if;
  return null;
end $$;
create trigger reviews_refresh after insert or update or delete on public.reviews
  for each row execute function private.reviews_refresh();

create or replace function private.bookings_refresh()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  perform private.refresh_mitra_stats(new.worker_id);
  return null;
end $$;
create trigger bookings_refresh after update of status on public.bookings
  for each row when (old.status is distinct from new.status)
  execute function private.bookings_refresh();

