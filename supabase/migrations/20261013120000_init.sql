-- Beresin — skema awal (sumber kebenaran tunggal, mengikuti kontrak di lib/).
--
-- Aturan ID: users.user_id SELALU = auth.uid(). Jadi customer_id, worker_id,
-- mitra_id, sender_id, reporter_id semuanya berisi UID login yang sama.
-- Role: customer (default) | admin (di-set manual via SQL). Mitra = punya baris
-- di public.mitras (dibuat admin lewat admin_review_application).

create schema if not exists private;
grant usage on schema private to anon, authenticated;

-- ───────────────────────── helpers ─────────────────────────

create or replace function private.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

