create or replace function private.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.users
    where user_id = (select auth.uid()) and role = 'admin'
  );
$$;

-- Client (auth_flow.dart) meng-upsert role='customer' tiap login; jangan biarkan
-- itu menurunkan admin, dan jangan biarkan user menaikkan role sendiri.
create or replace function private.guard_users()
returns trigger language plpgsql set search_path = '' as $$
begin
  if current_user in ('anon', 'authenticated') then
    if tg_op = 'INSERT' then
      new.role := 'customer';
    else
      new.role := old.role;
      new.user_id := old.user_id;
      new.auth_user_id := old.auth_user_id;
    end if;
  end if;
  return new;
end $$;

create trigger users_guard before insert or update on public.users
  for each row execute function private.guard_users();
create trigger users_updated_at before update on public.users
  for each row execute function private.set_updated_at();

