-- Pendaftar tidak boleh meng-approve dirinya sendiri / mengubah hasil review.
create or replace function private.guard_worker_applications()
returns trigger language plpgsql set search_path = '' as $$
begin
  if current_user in ('anon', 'authenticated') then
    if tg_op = 'UPDATE' then
      if old.status in ('approved', 'rejected') then
        raise exception 'pendaftaran yang sudah direview tidak bisa diubah';
      end if;
      new.user_id := old.user_id;
    end if;
    if new.status not in ('draft', 'submitted', 'pending') then
      raise exception 'status % hanya bisa di-set admin', new.status;
    end if;
    new.reviewer_note := case when tg_op = 'UPDATE' then old.reviewer_note end;
    new.reviewed_by   := case when tg_op = 'UPDATE' then old.reviewed_by end;
    new.reviewed_at   := case when tg_op = 'UPDATE' then old.reviewed_at end;
  end if;
  return new;
end $$;

